import { chromium } from "playwright";
const url = "https://miitiya.aether1013.dpdns.org/scarf.html";
const b = await chromium.launch({ channel: "chrome", args: ["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"] });
const ctx = await b.newContext({ viewport: { width: 700, height: 900 }, ignoreHTTPSErrors: false });
const p = await ctx.newPage();
const bad = [];
p.on("response", r => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().split("/").pop()}`); });
p.on("pageerror", e => bad.push("JS " + String(e).slice(0,100)));
const t0 = Date.now();
await p.goto(url, { waitUntil: "load", timeout: 90000 });
await p.waitForFunction(() => document.body.dataset.ready === "1", { timeout: 90000 });
console.log("ready", ((Date.now()-t0)/1000).toFixed(1) + "s", "| status:", await p.textContent("#status"));
await p.mouse.move(430, 400);
await p.waitForTimeout(2500);
console.log("errors:", bad.length ? bad.slice(0,4) : "none");
await p.screenshot({ path: "shots/tunnel_live.png" });
await b.close();
